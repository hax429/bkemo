import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  existsSync,
  promises as fsPromises,
  readFileSync,
} from 'node:fs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const CODIAN_SRC = path.resolve(__dirname, 'src/codian');

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
como — bkemo + Codian companion for Obsidian
*/
`;

const prod = process.argv[2] === 'production';
/** Local disposable-vault override only. Production builds must omit this. */
const devOrigin = process.env.BKEMO_DEV_ORIGIN || '';

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function getNamedImportAliases(contents, exportName, moduleNames) {
  const aliases = new Set([exportName]);
  const importPattern = /import\s*\{([^}]+)\}\s*from\s*["']([^"']+)["']/g;
  let match;

  while ((match = importPattern.exec(contents)) !== null) {
    const [, specifiers, moduleName] = match;
    if (!moduleNames.includes(moduleName)) continue;

    for (const specifier of specifiers.split(',')) {
      const parts = specifier.trim().split(/\s+as\s+/);
      if (parts[0] === exportName) {
        aliases.add(parts[1] ?? exportName);
      }
    }
  }

  return [...aliases];
}

function patchSdkImportMetaUrl(contents) {
  let patched = contents.replace(
    'createRequire(import.meta.url)',
    'createRequire(__filename)',
  );

  for (const alias of getNamedImportAliases(patched, 'createRequire', ['module', 'node:module'])) {
    patched = patched.replace(
      new RegExp(`\\b${escapeRegExp(alias)}\\(import\\.meta\\.url\\)`, 'g'),
      `${alias}(__filename)`,
    );
  }

  for (const alias of getNamedImportAliases(patched, 'fileURLToPath', ['url', 'node:url'])) {
    patched = patched.replace(
      new RegExp(`\\b${escapeRegExp(alias)}\\(import\\.meta\\.url\\)`, 'g'),
      '__filename',
    );
  }

  return patched;
}

const patchSdkImportMeta = {
  name: 'patch-sdk-import-meta',
  setup(build) {
    build.onLoad(
      {
        filter: /[\\/]node_modules[\\/](?:@openai[\\/]codex-sdk[\\/]dist[\\/]index\.js|@anthropic-ai[\\/]claude-agent-sdk[\\/]sdk\.mjs)$/,
      },
      async (args) => {
        const contents = await fsPromises.readFile(args.path, 'utf8');
        return {
          contents: patchSdkImportMetaUrl(contents),
          loader: 'js',
        };
      },
    );
  },
};

const mcpSdkPaths = {
  name: 'mcp-sdk-paths',
  setup(build) {
    build.onResolve({ filter: /^@modelcontextprotocol\/sdk\// }, (args) => {
      const subpath = args.path.slice('@modelcontextprotocol/sdk/'.length).replace(/\.js$/, '');
      const candidates = [
        path.join(__dirname, 'node_modules/@modelcontextprotocol/sdk/dist/esm', `${subpath}.js`),
        path.join(__dirname, 'node_modules/@modelcontextprotocol/sdk/dist/esm', subpath, 'index.js'),
      ];
      for (const candidate of candidates) {
        if (existsSync(candidate)) {
          return { path: candidate };
        }
      }
      return undefined;
    });
  },
};

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ['src/main.ts'],
  bundle: true,
  plugins: [mcpSdkPaths, patchSdkImportMeta],
  alias: {
    '@': CODIAN_SRC,
    '@codian': CODIAN_SRC,
  },
  external: [
    'obsidian',
    'electron',
    '@codemirror/autocomplete',
    '@codemirror/collab',
    '@codemirror/commands',
    '@codemirror/language',
    '@codemirror/lint',
    '@codemirror/search',
    '@codemirror/state',
    '@codemirror/view',
    '@lezer/common',
    '@lezer/highlight',
    '@lezer/lr',
    ...builtinModules,
    ...builtinModules.map((m) => `node:${m}`),
  ],
  format: 'cjs',
  target: 'es2021',
  logLevel: 'info',
  sourcemap: prod ? false : 'inline',
  treeShaking: true,
  outfile: 'main.js',
  minify: prod,
  define: {
    BKEMO_DEV_ORIGIN: JSON.stringify(devOrigin),
  },
  nodePaths: [
    path.join(__dirname, 'node_modules'),
  ],
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
